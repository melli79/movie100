            .fillMaxSize(),
        horizontalAlignment = Alignment.CenterHorizontally,
    ) {
        Text("Hi $login!")
        MovieSearchBar(login)
        MovieListComposable(login, modifier= Modifier.fillMaxSize())
    }
}
